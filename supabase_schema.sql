-- YLC BOYS HOSTEL: recommended normalized Supabase schema
-- Run in Supabase SQL Editor. This creates tables only; app credentials/auth wiring is the next step.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  full_name text not null,
  role text not null check (role in ('admin','manager','boarder')),
  created_at timestamptz not null default now()
);
create table if not exists public.boarders (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  name text not null, phone text, seat text, join_date date, nid text, guardian text,
  created_at timestamptz not null default now()
);
create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  text text not null, notice_date date not null default current_date,
  created_by uuid references public.profiles(id), created_at timestamptz default now()
);
create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  boarder_id bigint not null references public.boarders(id) on delete cascade,
  meal_date date not null, count numeric not null default 0, created_at timestamptz default now()
);
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  expense_date date not null, title text not null, amount numeric not null default 0,
  created_at timestamptz default now()
);
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  boarder_id bigint not null references public.boarders(id) on delete cascade,
  payment_date date not null, amount numeric not null default 0,
  method text not null check(method in ('Cash','Bkash','Nagad')),
  trx text, payment_type text not null default 'Meal Deposit', created_at timestamptz default now()
);
create table if not exists public.utilities (
  id bigint generated by default as identity primary key,
  boarder_id bigint not null references public.boarders(id) on delete cascade,
  bill_date date not null,
  bill_type text not null check(bill_type in ('Seat Rent','Current Bill','WiFi Bill','Khala Bill')),
  amount numeric not null default 0, method text, trx text, created_at timestamptz default now()
);

alter table public.profiles enable row level security;
alter table public.boarders enable row level security;
alter table public.notices enable row level security;
alter table public.meals enable row level security;
alter table public.expenses enable row level security;
alter table public.payments enable row level security;
alter table public.utilities enable row level security;

-- Helper functions used by RLS.
create or replace function public.my_role() returns text language sql stable security definer set search_path=public as $$
  select role from public.profiles where id = auth.uid()
$$;
create or replace function public.my_boarder_id() returns bigint language sql stable security definer set search_path=public as $$
  select id from public.boarders where user_id = auth.uid() limit 1
$$;

-- Profiles: users see themselves; admin sees all. Admin/manager may read profiles for operations.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated using (id=auth.uid() or public.my_role() in ('admin','manager'));
drop policy if exists profiles_admin_all on public.profiles;
create policy profiles_admin_all on public.profiles for all to authenticated using (public.my_role()='admin') with check (public.my_role()='admin');

-- Boarders: admin/manager full read/write; boarder only own row. Delete admin only.
drop policy if exists boarders_select on public.boarders;
create policy boarders_select on public.boarders for select to authenticated using (public.my_role() in ('admin','manager') or user_id=auth.uid());
drop policy if exists boarders_insert on public.boarders;
create policy boarders_insert on public.boarders for insert to authenticated with check (public.my_role() in ('admin','manager'));
drop policy if exists boarders_update on public.boarders;
create policy boarders_update on public.boarders for update to authenticated using (public.my_role() in ('admin','manager')) with check (public.my_role() in ('admin','manager'));
drop policy if exists boarders_delete on public.boarders;
create policy boarders_delete on public.boarders for delete to authenticated using (public.my_role()='admin');

-- Shared operational tables: admin/manager can write; boarders can only read their own meal/payment/utility rows.
drop policy if exists notices_select on public.notices;
create policy notices_select on public.notices for select to authenticated using (true);
drop policy if exists notices_write on public.notices;
create policy notices_write on public.notices for insert to authenticated with check (public.my_role() in ('admin','manager'));
drop policy if exists notices_update on public.notices;
create policy notices_update on public.notices for update to authenticated using (public.my_role() in ('admin','manager'));
drop policy if exists notices_delete on public.notices;
create policy notices_delete on public.notices for delete to authenticated using (public.my_role()='admin');

-- Expenses are visible to staff; boarder reports should expose only calculated totals through app logic/RPC later.
drop policy if exists expenses_staff on public.expenses;
create policy expenses_staff on public.expenses for select to authenticated using (public.my_role() in ('admin','manager'));
drop policy if exists expenses_insert on public.expenses;
create policy expenses_insert on public.expenses for insert to authenticated with check (public.my_role() in ('admin','manager'));
drop policy if exists expenses_update on public.expenses;
create policy expenses_update on public.expenses for update to authenticated using (public.my_role() in ('admin','manager'));
drop policy if exists expenses_delete on public.expenses;
create policy expenses_delete on public.expenses for delete to authenticated using (public.my_role()='admin');

-- Meals/payments/utilities row-level visibility.
DO $$ BEGIN
  EXECUTE 'drop policy if exists meals_select on public.meals';
  EXECUTE 'create policy meals_select on public.meals for select to authenticated using (public.my_role() in (''admin'',''manager'') or boarder_id=public.my_boarder_id())';
  EXECUTE 'drop policy if exists payments_select on public.payments';
  EXECUTE 'create policy payments_select on public.payments for select to authenticated using (public.my_role() in (''admin'',''manager'') or boarder_id=public.my_boarder_id())';
  EXECUTE 'drop policy if exists utilities_select on public.utilities';
  EXECUTE 'create policy utilities_select on public.utilities for select to authenticated using (public.my_role() in (''admin'',''manager'') or boarder_id=public.my_boarder_id())';
END $$;

-- Staff can insert/update operational rows; only admin can delete.
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['meals','payments','utilities'] LOOP
    EXECUTE format('drop policy if exists %I_staff_insert on public.%I',t,t);
    EXECUTE format('create policy %I_staff_insert on public.%I for insert to authenticated with check (public.my_role() in (''admin'',''manager''))',t,t);
    EXECUTE format('drop policy if exists %I_staff_update on public.%I',t,t);
    EXECUTE format('create policy %I_staff_update on public.%I for update to authenticated using (public.my_role() in (''admin'',''manager''))',t,t);
    EXECUTE format('drop policy if exists %I_admin_delete on public.%I',t,t);
    EXECUTE format('create policy %I_admin_delete on public.%I for delete to authenticated using (public.my_role()=''admin'')',t,t);
  END LOOP;
END $$;
